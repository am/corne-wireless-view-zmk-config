#!/usr/bin/env python3
"""Generate src/simple_view/assets.c and assets_list.h from the pixel sources in src/simple_view/assets/.

  icons.txt      icons as text, one character per pixel
  fonts/*.bdf    bitmap fonts (printable ASCII is kept)

Everything is 1 bit per pixel and is drawn to the screen pixel for pixel; nothing
is scaled or smoothed. Run this after editing icons.txt:

  python3 scripts/gen_simple_view_assets.py
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent / "src" / "simple_view"
ASSETS = ROOT / "assets"
FIRST, LAST = 32, 126


def pack(rows, width):
    """Rows of '#'/'.' to bytes, MSB = leftmost pixel, each row padded to a byte."""
    out = []
    for row in rows:
        row = row.ljust(width, ".")
        for i in range(0, width, 8):
            bits = row[i : i + 8].ljust(8, ".")
            out.append(sum(1 << (7 - b) for b, c in enumerate(bits) if c == "#"))
    return out


def c_array(name, data):
    lines = [f"static const uint8_t {name}[] = {{"]
    for i in range(0, len(data), 12):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 12]) + ",")
    lines.append("};")
    return "\n".join(lines)


def read_icons(path):
    icons, name = {}, None
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") and not set(line) <= {"#", "."}:
            continue
        if line.startswith("icon "):
            name = line.split()[1]
            icons[name] = []
        elif name is not None:
            if set(line) - {"#", "."}:
                raise SystemExit(f"{path}: bad row in icon {name}: {line!r}")
            icons[name].append(line)
    for name, rows in icons.items():
        if not rows or len({len(r) for r in rows}) != 1:
            raise SystemExit(f"{path}: icon {name} has rows of different widths")
    return icons


def read_bdf(path):
    """Return (ascent, descent, {codepoint: (advance, x offset, top, rows)}) for a BDF.

    top is the glyph box's first row counted down from the ascent line."""
    text = path.read_text(errors="replace")
    ascent = int(re.search(r"FONT_ASCENT (-?\d+)", text).group(1))
    descent = int(re.search(r"FONT_DESCENT (-?\d+)", text).group(1))
    glyphs = {}
    for block in text.split("STARTCHAR")[1:]:
        code = int(re.search(r"ENCODING (-?\d+)", block).group(1))
        if not FIRST <= code <= LAST:
            continue
        advance = int(re.search(r"DWIDTH (-?\d+)", block).group(1))
        w, h, x, y = map(int, re.search(r"BBX (-?\d+) (-?\d+) (-?\d+) (-?\d+)", block).groups())
        rows = []
        for hexrow in block.split("BITMAP")[1].split("ENDCHAR")[0].split():
            bits = bin(int(hexrow, 16))[2:].zfill(len(hexrow) * 4)
            rows.append("".join("#" if b == "1" else "." for b in bits[:w]))
        glyphs[code] = (advance, x, ascent - (y + h), rows)
    missing = [c for c in range(FIRST, LAST + 1) if c not in glyphs]
    if missing:
        raise SystemExit(f"{path}: missing glyphs {missing}")
    return ascent, descent, glyphs


def main():
    out = [
        "/* Generated by scripts/gen_simple_view_assets.py. Do not edit; edit the",
        " * sources in src/simple_view/assets/ and run the script again. */",
        "",
        '#include "assets.h"',
        "",
    ]

    for path in sorted((ASSETS / "fonts").glob("*.bdf")):
        ascent, descent, glyphs = read_bdf(path)
        name = f"font_{path.stem}"
        data, table = [], []
        for code in range(FIRST, LAST + 1):
            advance, x, top, rows = glyphs[code]
            width = len(rows[0]) if rows else 0
            table.append(f"    {{{len(data)}, {width}, {len(rows)}, {x}, {top}, {advance}}},")
            data += pack(rows, width)
        out += [
            c_array(f"{name}_data", data),
            f"static const struct sv_glyph {name}_glyphs[] = {{",
            *table,
            "};",
            f"const struct sv_font sv_{name} = {{{ascent}, {descent}, {FIRST}, {LAST - FIRST + 1}, {name}_glyphs, {name}_data}};",
            "",
        ]

    for name, rows in read_icons(ASSETS / "icons.txt").items():
        w, h = len(rows[0]), len(rows)
        out += [
            c_array(f"icon_{name}_data", pack(rows, w)),
            f"const struct sv_icon sv_icon_{name} = {{{w}, {h}, icon_{name}_data}};",
            "",
        ]

    (ROOT / "assets.c").write_text("\n".join(out))

    externs = re.findall(r"^const (struct sv_\w+ sv_\w+)", "\n".join(out), re.M)
    (ROOT / "assets_list.h").write_text(
        "/* Generated by scripts/gen_simple_view_assets.py. Do not edit. */\n\n"
        + "".join(f"extern const {e};\n" for e in externs)
    )


if __name__ == "__main__":
    main()
